const INSERT_SQL = `
  INSERT INTO equipment_items (name, slot, pack_id, image_asset)
  VALUES (?, ?, 'base', ?)
`;

/**
 * One-time seed of the cosmetic equipment-item catalog into `equipment_items`.
 * Runs synchronously on first launch only -- skipped once any row already exists,
 * same guard shape as `seedSpellsIfNeeded`.
 */
export function seedEquipmentItemsIfNeeded(sqliteDb: SQLiteDatabase): void {
  const existing = sqliteDb.getFirstSync<{ count: number }>(
    "SELECT COUNT(*) as count FROM equipment_items",
    []
  );
  if (existing && existing.count > 0) return;

  sqliteDb.withTransactionSync(() => {
    for (const [name, slot, imageAsset] of EQUIPMENT_CATALOG) {
      sqliteDb.runSync(INSERT_SQL, [name, slot, imageAsset]);
    }
  });
}
