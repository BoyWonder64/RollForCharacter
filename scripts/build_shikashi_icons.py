"""Slices Shikashi's Fantasy Icons Pack v2 (transparent sheet) into per-icon PNGs
for the Shikashi icon style and writes src/features/icons/shikashiAssets.ts.
Run: python scripts/build_shikashi_icons.py   (needs Pillow)
Sheet = 16 cols of 32x32; (row, col) below index that grid."""
import os
from PIL import Image

DIR = "pixel assets/Second Icon Set/Shikashi's Fantasy Icons Pack v2/"
SHEETS = {
  "shikashi": Image.open(DIR + "#2 - Transparent Icons & Drop Shadow.png").convert("RGBA"),
}

GROUPS = {
  "equipment": {  # keys = equipment slot names
    "Head": (7,1,"head"), "Body": (7,4,"body"), "Feet": (8,2,"feet"),
    "Left Hand": (5,1,"weapon"), "Right Hand": (6,1,"shield"),
    "Back": (7,14,"back"), "Accessory": (8,5,"accessory"),
  },
  "spell-schools": {
    "abjuration": (3,7,"abjuration"), "conjuration": (21,0,"conjuration"),
    "divination": (18,4,"divination"), "enchantment": (0,6,"enchantment"),
    "evocation": (3,9,"evocation"), "illusion": (3,14,"illusion"),
    "necromancy": (0,0,"necromancy"), "transmutation": (19,8,"transmutation"),
  },
  "tabs": {
    "characters": (7,1,"characters"), "dice-roller": (13,13,"dice-roller"),
    "encounter": (5,9,"encounter"), "settings": (10,9,"settings"),
    "party": (4,2,"party"),
  },
  "campaign-items": {
    "potion": (9,0,"potion"), "key": (11,9,"key"), "book": (13,0,"book"),
    "scroll": (13,10,"scroll"), "gem": (12,15,"gem"), "coin": (12,7,"coin"),
    "material": (17,0,"material"), "food": (14,0,"food"), "chest": (11,11,"chest"),
    "necklace": (8,6,"necklace"), "sword": (5,1,"sword"), "shield": (6,2,"shield"),
  },
  "conditions": {
    "blinded": (0,2,"blinded"), "charmed": (0,6,"charmed"), "deafened": (0,3,"deafened"),
    "frightened": (0,4,"frightened"), "grappled": (1,4,"grappled"),
    "incapacitated": (2,1,"incapacitated"), "invisible": (7,14,"invisible"),
    "paralyzed": (0,8,"paralyzed"), "petrified": (17,1,"petrified"),
    "poisoned": (0,1,"poisoned"), "prone": (3,13,"prone"), "restrained": (11,2,"restrained"),
    "stunned": (0,5,"stunned"), "unconscious": (0,7,"unconscious"),
    "exhaustion": (0,10,"exhaustion"),
  },
}

def cell(sheet, r, c):
    return sheet.crop((c*32, r*32, c*32+32, r*32+32))

STYLES = list(SHEETS)
for style in STYLES:
    for group, items in GROUPS.items():
        d = f"assets/icons/{style}/{group}"; os.makedirs(d, exist_ok=True)
        for key, (r, c, fname) in items.items():
            cell(SHEETS[style], r, c).save(f"{d}/{fname}.png")

lines = ["// GENERATED by scripts/build_shikashi_icons.py -- do not edit by hand.",
         "// Shikashi's Fantasy Icons Pack v2 (see docs/ICON_PACKS.md).", ""]
for style, const in (("shikashi", "SHIKASHI"),):
    for group, items in GROUPS.items():
        name = f"{const}_{group.upper().replace('-', '_')}"
        lines.append(f"export const {name}: Record<string, number> = {{")
        for key, (r, c, fname) in items.items():
            lines.append(f'  "{key}": require("../../../assets/icons/{style}/{group}/{fname}.png"),')
        lines.append("};\n")
open("src/features/icons/shikashiAssets.ts", "w").write("\n".join(lines))
print("ok")
